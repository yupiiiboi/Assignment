import math
num = float(input("Enter a number: "))

square_root = math.sqrt(num)
log_value = math.log(num)      
sine_value = math.sin(num)     

print(f"Square root: {square_root}")
print(f"Logarithm: {log_value}")
print(f"Sine: {sine_value}")
